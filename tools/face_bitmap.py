#!/usr/bin/env python3
"""
Portrait PNG -> 1-bit C header for the Settings ABOUT screen
===========================================================
Usage
-----
  # Render the SVG to a PNG first (macOS Quick Look does it without extra tools):
  qlmanage -t -s 1024 -o /tmp face.svg
  python3 tools/face_bitmap.py /tmp/face.svg.png \
      devices/multi_function_remote/src/about_face.h --heights 64 104

Dark pixels of the image become lit pixels on the OLED. The image is cropped
to its dark content, scaled to each of --heights and packed MSB-first, one
row at a time (each row padded to whole bytes); one array per height,
ABOUT_FACE_<h>. Needs Pillow.
"""
import argparse
from PIL import Image


def pack(src, h, threshold):
    w = max(1, round(h * src.width / src.height))
    im = src.resize((w, h), Image.LANCZOS)
    stride = (w + 7) // 8
    data = []
    for y in range(h):
        row = [0] * stride
        for x in range(w):
            if im.getpixel((x, y)) < threshold:
                row[x // 8] |= 0x80 >> (x % 8)
        data += row
    lines = ['    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + stride]) + ','
             for i in range(0, len(data), stride)]
    return w, stride, data, (f'''
// {w}x{h}, rows of {stride} bytes
static const int ABOUT_FACE_{h}_W = {w};
static const int ABOUT_FACE_{h}_STRIDE = {stride};
static const uint8_t ABOUT_FACE_{h}[] = {{
''' + '\n'.join(lines) + '\n};\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('png')
    ap.add_argument('header')
    ap.add_argument('--heights', type=int, nargs='+', default=[64, 104])
    ap.add_argument('--threshold', type=int, default=140)
    a = ap.parse_args()

    im = Image.open(a.png).convert('L')
    box = Image.eval(im, lambda v: 255 if v < a.threshold else 0).getbbox()
    im = im.crop(box)

    out = '''#pragma once
#include <cstdint>

// Portrait for the Settings ABOUT screen, 1 bit per pixel (1 = lit), MSB =
// leftmost pixel, one array per height (ABOUT_FACE_<h>). Generated by
// tools/face_bitmap.py from the blog's face.svg - regenerate, don't edit.
'''
    total = 0
    for h in a.heights:
        w, stride, data, text = pack(im, h, a.threshold)
        out += text
        total += len(data)
        print(f'{w}x{h}, {len(data)} bytes')
    with open(a.header, 'w') as f:
        f.write(out)
    print(f'{total} bytes -> {a.header}')


if __name__ == '__main__':
    main()
